#!/usr/bin/env python3
"""transpile.py — Convert between GdTest, GUT, and gdUnit4 test formats.

Single-file usage:
    # GdTest -> other format
    python3 benchmarks/transpile.py --target gut     <src.gd> > out.gd
    python3 benchmarks/transpile.py --target gdunit4 <src.gd> > out.gd

    # GUT or gdUnit4 -> GdTest
    python3 benchmarks/transpile.py --source gut     <src.gd> > out.gd
    python3 benchmarks/transpile.py --source gdunit4 <src.gd> > out.gd

Directory usage:
    # Migrate an entire directory from GUT or gdUnit4 to GdTest (in-place)
    python3 benchmarks/transpile.py --source gut     test/cases/
    python3 benchmarks/transpile.py --source gdunit4 test/cases/

    # Dry-run: show what would change without writing anything (exits 1 if any file differs)
    python3 benchmarks/transpile.py --source gut     --check test/cases/

    # Convert a directory of GdTest files to GUT or gdUnit4 (writes to output dir)
    python3 benchmarks/transpile.py --target gut     --output-dir /tmp/gut-tests test/cases/
    python3 benchmarks/transpile.py --target gdunit4 --output-dir /tmp/gdunit4-tests test/cases/

WARNING: --source on a directory rewrites files in place.
Use `git restore .` or `git checkout -- <dir>` to revert.

--target: source must use GdTest base class (extends GdTest).
--source: source uses GUT or gdUnit4 base class; output is GdTest.
          Auto-generated files (produced by --target) round-trip cleanly.
          Native GUT/gdUnit4 files: common assertions are rewritten; complex
          patterns (method chains spanning multiple lines) may need manual cleanup.

# TODO(next): 3 tests fail in GUT (58/61) due to --isolation=test semantics that GUT can't
# replicate in a single process: (1) physics delta in headless completes a 0.05s windup in
# one frame; (2) GameClock.current_tick accumulates across tests causing off-by-one timer
# assertions; (3) stale command_buffer from previous tests affects corpse-targeting checks.
# Fix would require injecting a before_each() that resets game-specific singleton state.
"""

import argparse
import difflib
import os
import re
import sys

GUT_HEADER = """\
# auto-generated by benchmarks/transpile.py — do not edit
# source: {src}
extends GutTest

# GutTest already defines: wait_physics_frames, assert_eq/ne/true/false/null/not_null,
# assert_almost_eq, add_child_autofree. Only add the methods it lacks.

func wait_physics_seconds(s: float) -> void:
\tawait wait_seconds(s)

func wait_process_frame() -> void:
\tawait wait_process_frames(1)

func instantiate_scene(packed: PackedScene) -> Node:
\tvar n := packed.instantiate()
\tadd_child_autofree(n)
\treturn n

# GUT's add_child_autofree returns untyped Variant; override with -> Node so that
# `var x := add_child_autofree(...)` can infer the type in strict mode.
func add_child_autofree(node: Node, legible_unique_name: bool = false) -> Node:
\tsuper.add_child_autofree(node, legible_unique_name)
\treturn node

func assert_approx(a, b, t=1e-6, msg='') -> void:
\tassert_almost_eq(a, b, t, str(msg))

func assert_lt(a, b, msg='') -> void:
\tassert_true(a < b, str('[', a, '] expected < [', b, ']: ', msg))

func assert_lte(a, b, msg='') -> void:
\tassert_true(a <= b, str('[', a, '] expected <= [', b, ']: ', msg))

func assert_gt(a, b, msg='') -> void:
\tassert_true(a > b, str('[', a, '] expected > [', b, ']: ', msg))

func assert_gte(a, b, msg='') -> void:
\tassert_true(a >= b, str('[', a, '] expected >= [', b, ']: ', msg))

"""

GDUNIT4_HEADER = """\
# auto-generated by benchmarks/transpile.py — do not edit
# source: {src}
extends GdUnitTestSuite

func assert_eq(a: Variant, b: Variant, _m: String = "") -> bool:
\tassert_that(a).is_equal(b)
\treturn a == b

func assert_ne(a: Variant, b: Variant, _m: String = "") -> bool:
\tassert_that(a).is_not_equal(b)
\treturn a != b

func assert_lt(a: Variant, b: Variant, _m: String = "") -> bool:
\tassert_that(a).is_less(b)
\treturn a < b

func assert_lte(a: Variant, b: Variant, _m: String = "") -> bool:
\tassert_that(a).is_less_equal(b)
\treturn a <= b

func assert_gt(a: Variant, b: Variant, _m: String = "") -> bool:
\tassert_that(a).is_greater(b)
\treturn a > b

func assert_ge(a: Variant, b: Variant, _m: String = "") -> bool:
\tassert_that(a).is_greater_equal(b)
\treturn a >= b

func assert_gte(a: Variant, b: Variant, _m: String = "") -> bool:
\treturn assert_ge(a, b, _m)

func assert_approx(a: float, b: float, t: float = 1e-6, _m: String = "") -> bool:
\tassert_float(a).is_equal_approx(b, t)
\treturn absf(a - b) <= t

func assert_almost_eq(a: float, b: float, t: float = 1e-6, m: String = "") -> bool:
\treturn assert_approx(a, b, t, m)

func assert_true(c: bool, _m: String = "") -> bool:
\tassert_bool(c).is_true()
\treturn c

func assert_false(c: bool, _m: String = "") -> bool:
\tassert_bool(c).is_false()
\treturn not c

func assert_null(v: Variant, _m: String = "") -> bool:
\tassert_that(v).is_null()
\treturn v == null

func assert_not_null(v: Variant, _m: String = "") -> bool:
\tassert_that(v).is_not_null()
\treturn v != null

func fail(m: String = "explicit fail") -> void:
\tassert_bool(false).is_true()

func add_child_autofree(node: Node) -> Node:
\tadd_child(auto_free(node))
\treturn node

func instantiate_scene(packed: PackedScene) -> Node:
\tvar n := packed.instantiate()
\tadd_child(auto_free(n))
\treturn n

func wait_physics_frames(n: int = 1) -> void:
\tfor _i in range(n):
\t\tawait get_tree().physics_frame

func wait_physics_seconds(s: float) -> void:
\tawait get_tree().create_timer(s).timeout

func wait_process_frame() -> void:
\tawait await_idle_frame()

"""


def transpile(src_path: str, target: str) -> str:
    with open(src_path, encoding="utf-8") as f:
        lines = f.readlines()

    if target == "gut":
        header = GUT_HEADER.format(src=src_path)
    else:
        header = GDUNIT4_HEADER.format(src=src_path)

    out = []
    for line in lines:
        # Drop the extends GdTest line — the header already sets the base class.
        if re.match(r"^\s*extends\s+GdTest\s*$", line):
            continue
        out.append(line)

    # Strip leading blank lines from the body so the file starts cleanly after the header.
    while out and out[0].strip() == "":
        out.pop(0)

    return header + "".join(out)


# ---------------------------------------------------------------------------
# Source direction: GUT/gdUnit4 → GdTest
# ---------------------------------------------------------------------------

def _func_names_from_header(header: str) -> set:
    return set(re.findall(r"^func (\w+)\(", header, re.MULTILINE))


def _standalone_header_comments(header: str) -> frozenset:
    """Comment lines in the header that live outside any func body."""
    skip = ("# auto-generated", "# source:")
    comments = set()
    in_func = False
    for raw in header.splitlines():
        line = raw.rstrip()
        if re.match(r"^func \w+\(", line):
            in_func = True
            continue
        if in_func and line and line[0] not in "\t ":
            in_func = False
        if in_func:
            continue
        if line.startswith("#") and not any(line.startswith(p) for p in skip):
            comments.add(line)
    return frozenset(comments)


def _strip_compat_funcs(lines: list, func_names: set) -> list:
    """Remove every func block whose name appears in func_names."""
    result = []
    i = 0
    while i < len(lines):
        m = re.match(r"^func (\w+)\(", lines[i])
        if m and m.group(1) in func_names:
            i += 1
            # Consume body (indented lines) and trailing blank lines.
            while i < len(lines) and (not lines[i].strip() or lines[i][0] in "\t "):
                i += 1
        else:
            result.append(lines[i])
            i += 1
    return result


def _rewrite_gut(lines: list) -> list:
    out = []
    for line in lines:
        # assert_almost_eq shares arg order with assert_approx — just rename.
        line = re.sub(r"\bassert_almost_eq\b", "assert_approx", line)
        # GUT's wait_seconds → GdTest's wait_physics_seconds.
        line = re.sub(r"\bwait_seconds\b", "wait_physics_seconds", line)
        # GUT's wait_process_frames(1) → GdTest's wait_process_frame().
        line = re.sub(r"\bwait_process_frames\(1\)", "wait_process_frame()", line)
        out.append(line)
    return out


_GDUNIT4_FLUENT = [
    (r"\bassert_that\((.+?)\)\.is_equal\((.+?)\)",              r"assert_eq(\1, \2)"),
    (r"\bassert_that\((.+?)\)\.is_not_equal\((.+?)\)",          r"assert_ne(\1, \2)"),
    (r"\bassert_that\((.+?)\)\.is_null\(\)",                    r"assert_null(\1)"),
    (r"\bassert_that\((.+?)\)\.is_not_null\(\)",                r"assert_not_null(\1)"),
    (r"\bassert_that\((.+?)\)\.is_less\((.+?)\)",               r"assert_lt(\1, \2)"),
    (r"\bassert_that\((.+?)\)\.is_less_equal\((.+?)\)",         r"assert_lte(\1, \2)"),
    (r"\bassert_that\((.+?)\)\.is_greater\((.+?)\)",            r"assert_gt(\1, \2)"),
    (r"\bassert_that\((.+?)\)\.is_greater_equal\((.+?)\)",      r"assert_gte(\1, \2)"),
    (r"\bassert_bool\((.+?)\)\.is_true\(\)",                    r"assert_true(\1)"),
    (r"\bassert_bool\((.+?)\)\.is_false\(\)",                   r"assert_false(\1)"),
    (r"\bassert_float\((.+?)\)\.is_equal_approx\((.+?),\s*(.+?)\)", r"assert_approx(\1, \2, \3)"),
]


def _rewrite_gdunit4(lines: list) -> list:
    out = []
    for line in lines:
        for pat, repl in _GDUNIT4_FLUENT:
            line = re.sub(pat, repl, line)
        out.append(line)
    return out


def transpile_from(src_path: str, source: str) -> str:
    # utf-8-sig strips a leading BOM, which PowerShell's > redirect adds on Windows.
    with open(src_path, encoding="utf-8-sig") as f:
        lines = f.readlines()

    if source == "gut":
        foreign_extends = r"^\s*extends\s+GutTest\s*$"
        compat_funcs = _func_names_from_header(GUT_HEADER)
        header_comments = _standalone_header_comments(GUT_HEADER)
        rewrite = _rewrite_gut
    else:
        foreign_extends = r"^\s*extends\s+GdUnitTestSuite\s*$"
        compat_funcs = _func_names_from_header(GDUNIT4_HEADER)
        header_comments = _standalone_header_comments(GDUNIT4_HEADER)
        rewrite = _rewrite_gdunit4

    out = []
    for line in lines:
        if re.match(r"^# auto-generated by benchmarks/transpile\.py", line):
            continue
        if re.match(r"^# source:", line):
            continue
        if re.match(foreign_extends, line):
            continue
        if line.rstrip() in header_comments:
            continue
        out.append(line)

    out = _strip_compat_funcs(out, compat_funcs)
    out = rewrite(out)

    while out and not out[0].strip():
        out.pop(0)

    return "extends GdTest\n\n" + "".join(out)


def _discover_gd_files(directory: str) -> list[str]:
    """Recursively find all .gd files under directory, sorted for determinism."""
    result = []
    for root, _dirs, files in os.walk(directory):
        for name in files:
            if name.endswith(".gd"):
                result.append(os.path.join(root, name))
    return sorted(result)


def _run_directory(args) -> None:
    files = _discover_gd_files(args.src)
    if not files:
        print(f"transpile: no .gd files found under {args.src}", file=sys.stderr)
        sys.exit(1)

    if args.target:
        # --target + directory: write converted files to --output-dir
        if not args.output_dir:
            print("transpile: --target on a directory requires --output-dir", file=sys.stderr)
            sys.exit(1)
        os.makedirs(args.output_dir, exist_ok=True)
        for src in files:
            result = transpile(src, args.target)
            rel = os.path.relpath(src, args.src)
            dst = os.path.join(args.output_dir, rel)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            with open(dst, "w", encoding="utf-8") as f:
                f.write(result)
            print(f"  wrote {dst}", file=sys.stderr)
    else:
        # --source + directory: in-place rewrite (or --check dry-run)
        any_diff = False
        for src in files:
            with open(src, encoding="utf-8-sig") as f:
                original = f.read()
            result = transpile_from(src, args.source)
            if result == original:
                continue
            if args.check:
                diff = difflib.unified_diff(
                    original.splitlines(keepends=True),
                    result.splitlines(keepends=True),
                    fromfile=src,
                    tofile=src + " (transpiled)",
                )
                sys.stdout.writelines(diff)
                any_diff = True
            else:
                with open(src, "w", encoding="utf-8") as f:
                    f.write(result)
                print(f"  rewrote {src}", file=sys.stderr)
        if args.check and any_diff:
            sys.exit(1)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--target", choices=["gut", "gdunit4"],
                       help="Convert GdTest source to GUT or gdUnit4")
    group.add_argument("--source", choices=["gut", "gdunit4"],
                       help="Convert GUT or gdUnit4 source back to GdTest")
    parser.add_argument("src", help="Source .gd file or directory")
    parser.add_argument("--output-dir", metavar="DIR",
                        help="Output directory (required for --target on a directory)")
    parser.add_argument("--check", action="store_true",
                        help="Dry-run: print unified diff, exit 1 if any file would change")
    args = parser.parse_args()

    if os.path.isdir(args.src):
        _run_directory(args)
        return

    if args.check:
        print("transpile: --check is only meaningful for directory input", file=sys.stderr)
        sys.exit(1)

    if args.target:
        print(transpile(args.src, args.target), end="")
    else:
        print(transpile_from(args.src, args.source), end="")


if __name__ == "__main__":
    main()
